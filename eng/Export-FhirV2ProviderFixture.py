#!/usr/bin/env python3
"""Export the committed bounded V1 composition into an SDK-independent V2 test provider.

This does not add a production generator mode or claim complete R4 support.
Common primitive implementations are copied with explicit provenance for the fixture.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = "Tests/FhirVersions/V2/Provider/Generated"
INPUT = "Tests/Architecture/V1/Generated/R4ExperimentComposition.g.cs"


def generate():
    text = (ROOT / INPUT).read_text(encoding="utf-8")
    text = text.replace("using MyFhirSdk.ModelMetadata;", "using MyFhirSdk.ModelContracts;")
    text = text.replace("using MyFhirSdk.Primitives;\n", "").replace("using MyFhirSdk.Validation.Rules;\n", "")
    text = text.replace("MyFhirSdk.Tests.Architecture.V1", "MyFhirSdk.Tests.FhirVersions.V2")
    text = text.replace("internal static class R4ExperimentComposition", "public static class R4ProviderFixture")
    text = text.replace("    internal ", "    public ")
    text = text.replace("public static PrimitiveRegistry CreatePrimitives() => PrimitiveRegistry.Create([",
        "public static PrimitiveProviderDefinition CreatePrimitives() => new(Identity, [")
    text = text.replace("public static ImmutableModelMetadataProvider CreateMetadata() => new(\n",
        "public static ModelMetadataDefinition CreateMetadata() => new(Identity,\n"
        "        ModelTypes.Concat(CreatePrimitives().Definitions.Select(p => p.PrimitiveType)),\n")
    for old, new in (("ResourceTypeMetadata", "ResourceDefinition"), ("DeclaredDataTypeMetadata", "DeclaredDataTypeDefinition"),
                     ("ExtensionValueMetadata", "ExtensionValueDefinition"), ("IValidationRuleProvider", "ValidationProviderDefinition"),
                     ("IFhirValidationRule", "ValidationRuleDefinition")):
        text = text.replace(old, new)
    text = text.replace("    public const string PackageId", '    public static ModelIdentity Identity { get; } = new("4.0.1", "hl7.fhir.r4.core", "4.0.1", "r4-v1-fixture", "r4-v1-selected");\n    public const string PackageId')
    text = text.replace("// <auto-generated /> V1 experiment only.", "// <auto-generated /> V2 bounded provider fixture; see eng/Export-FhirV2ProviderFixture.py.")
    outputs = {f"{OUT}/R4ProviderFixture.g.cs": text}
    inputs = [INPUT, "ModelSupport/PrimitiveCodecs.cs", "ModelSupport/PrimitiveValidators.cs", "ModelSupport/PrimitiveValueAccess.cs"]
    for name in inputs[1:3]:
        content = (ROOT / name).read_text(encoding="utf-8")
        content = content.replace("namespace MyFhirSdk.ModelSupport;", "namespace MyFhirSdk.Tests.FhirVersions.V2;")
        content = content.replace("PrimitiveCodecException", "ProviderFixtureException").replace("public static", "internal static")
        content = "// <auto-generated /> Test-only copy of " + name + ".\n#nullable enable\n" + content
        outputs[f"{OUT}/{Path(name).stem}.g.cs"] = content
    helper = (ROOT / inputs[-1]).read_text(encoding="utf-8").split("internal static class PrimitiveValueAccess", 1)[1]
    outputs[f"{OUT}/PrimitiveValueAccess.g.cs"] = "// <auto-generated /> Test-only primitive accessor helper.\n#nullable enable\nusing MyFhirSdk.Core;\nnamespace MyFhirSdk.Tests.FhirVersions.V2;\ninternal static class PrimitiveValueAccess" + helper
    sha = lambda data: hashlib.sha256(data).hexdigest()
    manifest = {"productionR4Support": False, "inputHashNormalization": "utf8-lf",
                "inputs": [{"path": p, "sha256": sha((ROOT / p).read_text(encoding="utf-8").encode())} for p in inputs],
                "sources": [{"path": p, "sha256": sha(s.encode())} for p, s in sorted(outputs.items())]}
    outputs[f"{OUT}/fixture-manifest.json"] = json.dumps(manifest, indent=2) + "\n"
    return outputs


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if set(p.relative_to(ROOT).as_posix() for p in (ROOT / OUT).glob("*")) - generated.keys():
        raise ValueError("Unexpected generated fixture files")
    for name, content in generated.items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_bytes() != content.encode():
                raise ValueError(f"Fixture drift: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode())
    print(f"V2 fixture {'verified' if args.check else 'exported'}: {len(generated)} files")
