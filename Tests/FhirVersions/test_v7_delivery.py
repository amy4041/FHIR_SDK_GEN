ROOT = Path(__file__).resolve().parents[2]


def module(name, path):
    spec = importlib.util.spec_from_file_location(name, ROOT / path)
    value = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(value)
    return value


delivery = module("v7", "eng/Test-FhirV7Delivery.py")
comparison = module("v7_compare", "eng/Compare-FhirV7Delivery.py")


class DeliveryEvidenceTests(unittest.TestCase):
    def legs(self, directory):
        windows, linux = directory / "windows", directory / "linux"
        for root in (windows, linux):
            root.mkdir()
            (root / "summary.json").write_text("{}", encoding="utf-8")
            for release in ("R4", "R5"):
                (root / (release + "-generated-hashes.json")).write_text('{"Patient.cs":"same"}', encoding="utf-8")
            (root / "rollback-source-hashes.json").write_text(json.dumps({"source.cs": "a" * 64}), encoding="utf-8")
        a = {"os": "Windows", "sourceRevision": "current", "portableSourceFingerprint": {"sha256": "source"},
            "sdkVersion": "9.0.317", "targetFramework": "net9.0", "configuration": "Release", "toolVersion": "1.3.1",
            "toolPackageSha256": "canonical", "runtimeContract": {"sha256": "reference"}, "policies": {"policy": "locked"},
            "testCounts": {"passed": 1170, "failed": 0}, "freshV5Tests": 81, "freshV6Tests": 92,
            "rollback": {"sourceRevision": delivery.ROLLBACK_REVISION, "archiveSha256": "archive", "testCounts": {"passed": 1170},
                "assemblies": ["tests"], "sourceFiles": 1},
            "generation": {"R4": {}, "R5": {}}, "externalServerAcceptance": "Pending"}
        b = copy.deepcopy(a)
        b["os"] = "Linux"
        return windows, linux, a, b

    def test_cross_platform_acceptance_keeps_external_server_pending(self):
        with tempfile.TemporaryDirectory() as temp:
            windows, linux, a, b = self.legs(Path(temp))
            with patch.object(comparison, "validate_leg", side_effect=[a, b]):
                result = comparison.compare(windows, linux)
            self.assertEqual("Passed", result["status"])
            self.assertEqual("Pending", result["externalServerAcceptance"])

    def test_two_copies_of_windows_cannot_claim_cross_platform(self):
        with tempfile.TemporaryDirectory() as temp:
            windows, linux, a, b = self.legs(Path(temp))
            b["os"] = "Windows"
            with patch.object(comparison, "validate_leg", side_effect=[a, b]), self.assertRaisesRegex(ValueError, "distinct"):
                comparison.compare(windows, linux)

    def test_mixed_source_tool_contract_and_policy_are_rejected(self):
        for key in ("sourceRevision", "portableSourceFingerprint", "toolPackageSha256", "runtimeContract", "policies", "sdkVersion"):
            with self.subTest(key=key), tempfile.TemporaryDirectory() as temp:
                windows, linux, a, b = self.legs(Path(temp))
                b[key] = "different"
                with patch.object(comparison, "validate_leg", side_effect=[a, b]), self.assertRaisesRegex(ValueError, "mismatch"):
                    comparison.compare(windows, linux)

    def test_changed_generated_byte_is_rejected(self):
        with tempfile.TemporaryDirectory() as temp:
            windows, linux, a, b = self.legs(Path(temp))
            (linux / "R4-generated-hashes.json").write_text('{"Patient.cs":"changed"}', encoding="utf-8")
            with patch.object(comparison, "validate_leg", side_effect=[a, b]), self.assertRaisesRegex(ValueError, "generated bytes"):
                comparison.compare(windows, linux)

    def test_tar_container_hash_difference_does_not_reject_identical_rollback_sources(self):
        with tempfile.TemporaryDirectory() as temp:
            windows, linux, a, b = self.legs(Path(temp))
            b["rollback"]["archiveSha256"] = "different tar metadata"
            with patch.object(comparison, "validate_leg", side_effect=[a, b]):
                self.assertEqual("Passed", comparison.compare(windows, linux)["status"])

    def test_rollback_revision_counts_assemblies_and_file_count_still_must_match(self):
        for key, value in (("sourceRevision", "another commit"), ("testCounts", {"passed": 1}),
                           ("assemblies", ["Other.Tests"]), ("sourceFiles", 2)):
            with self.subTest(key=key), tempfile.TemporaryDirectory() as temp:
                windows, linux, a, b = self.legs(Path(temp))
                b["rollback"][key] = value
                with patch.object(comparison, "validate_leg", side_effect=[a, b]), self.assertRaisesRegex(ValueError, "Rollback mismatch: " + key):
                    comparison.compare(windows, linux)

    def test_changed_or_renamed_rollback_source_is_rejected_with_the_path(self):
        for hashes in ({"source.cs": "b" * 64}, {"renamed.cs": "a" * 64}):
            with self.subTest(hashes=hashes), tempfile.TemporaryDirectory() as temp:
                windows, linux, a, b = self.legs(Path(temp))
                (linux / "rollback-source-hashes.json").write_text(json.dumps(hashes), encoding="utf-8")
                with patch.object(comparison, "validate_leg", side_effect=[a, b]), self.assertRaisesRegex(ValueError, r"Rollback source files differ: .*source.cs"):
                    comparison.compare(windows, linux)

    def test_rollback_archive_ignores_inherited_git_line_ending_configuration(self):
        # The shared integrity suite also runs in V1's depth-1 checkout.
        # Test real Git conversion with a self-contained commit, not production history.
        with tempfile.TemporaryDirectory(prefix="MyFhirSdk-V7-Git-") as temporary, patch.dict(os.environ):
            repository = Path(temporary)
            for name in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_OBJECT_DIRECTORY",
                         "GIT_ALTERNATE_OBJECT_DIRECTORIES", "GIT_COMMON_DIR", "GIT_SHALLOW_FILE"):
                os.environ.pop(name, None)

            def git(*arguments, check=True):
                return subprocess.run(["git", "-c", "core.autocrlf=false", "-c", "core.eol=lf", *arguments],
                    cwd=repository, check=check, stdout=subprocess.PIPE, stderr=subprocess.PIPE)

            git("init", "--template=")
            text = b'{"fixture":true}\n'
            binary = b"\x00\xff\r\n\x01binary\r\n"
            (repository / "fixture.json").write_bytes(text)
            (repository / "payload.bin").write_bytes(binary)
            hooks = repository / "empty-hooks"
            hooks.mkdir()
            git("add", "--", "fixture.json", "payload.bin")
            git("-c", "user.name=V7 test", "-c", "user.email=v7-test@example.invalid", "-c", "commit.gpgsign=false",
                "-c", "core.hooksPath=" + str(hooks), "commit", "-m", "Create archive test fixture")
            revision = git("rev-parse", "HEAD").stdout.decode().strip()
            self.assertNotEqual(0, git("cat-file", "-e", delivery.ROLLBACK_REVISION + "^{commit}", check=False).returncode)

            archives = []
            inherited_count = int(os.environ.get("GIT_CONFIG_COUNT", "0"))
            with patch.object(delivery, "ROOT", repository), patch.object(delivery, "ROLLBACK_REVISION", revision):
                for autocrlf, eol in (("true", "crlf"), ("false", "lf")):
                    settings = {"GIT_CONFIG_COUNT": str(inherited_count + 2), f"GIT_CONFIG_KEY_{inherited_count}": "core.autocrlf",
                        f"GIT_CONFIG_VALUE_{inherited_count}": autocrlf, f"GIT_CONFIG_KEY_{inherited_count + 1}": "core.eol",
                        f"GIT_CONFIG_VALUE_{inherited_count + 1}": eol}
                    with patch.dict(os.environ, settings):
                        data = delivery.archive_rollback_source()
                    with tarfile.open(fileobj=io.BytesIO(data)) as archive:
                        self.assertEqual(text, archive.extractfile("fixture.json").read())
                        self.assertEqual(hashlib.sha256(binary).hexdigest(), hashlib.sha256(archive.extractfile("payload.bin").read()).hexdigest())
                    archives.append(data)
            self.assertEqual(archives[0], archives[1])

    def test_tampered_canonical_package_is_rejected_before_comparison(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / "summary.json").write_text(json.dumps({"gate": "G7-platform", "status": "Passed", "os": "Windows", "toolPackageSha256": "old"}), encoding="utf-8")
            (root / "canonical-tool.nupkg").write_bytes(b"changed")
            with self.assertRaisesRegex(ValueError, "package hash"):
                comparison.validate_leg(root)

    def test_stale_g6_fingerprint_is_rejected_before_report_reuse(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / "summary.json").write_text(json.dumps({"gate": "G6", "status": "Passed", "sourceFingerprint": "old"}), encoding="utf-8")
            with self.assertRaisesRegex(ValueError, "fingerprint"):
                delivery.validate_prerequisite(root, "current")

    def test_trx_counter_tampering_is_rejected(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / "test.trx").write_text('''<TestRun><TestDefinitions><UnitTest><TestMethod codeBase="Tests.dll" /></UnitTest></TestDefinitions>
                <Results><UnitTestResult testName="One" outcome="Passed" /></Results>
                <ResultSummary><Counters total="2" passed="2" failed="0" /></ResultSummary></TestRun>''', encoding="utf-8")
            with self.assertRaisesRegex(ValueError, "counters"):
                comparison.check_reports(root, {"Tests"}, {"total": 2, "passed": 2, "failed": 0, "skipped": 0})

    def test_deployment_rejects_an_assembly_loaded_from_another_directory(self):
        with tempfile.TemporaryDirectory() as temp:
            directory = Path(temp) / "deployment"
            directory.mkdir()
            required = delivery.SHARED_DLLS | {"MyFhirSdk.R4.Models.dll"}
            for name in required:
                (directory / name).write_bytes(b"implementation")
            result = {"status": "Passed", "releases": [{"fhirVersion": "4.0.1", "modelAssembly": "MyFhirSdk.R4.Models", "roundTrip": True,
                "validation": True, "typedClient": True}], "assemblies": [{"name": Path(n).stem, "path": str(directory / n)} for n in required]}
            self.assertEqual(required, delivery.check_deployment(result, "R4", directory))
            result["assemblies"][0]["path"] = str(Path(temp) / "cache" / "MyFhirSdk.dll")
            with self.assertRaisesRegex(ValueError, "outside"):
                delivery.check_deployment(result, "R4", directory)

    def test_portable_fingerprint_normalizes_text_but_preserves_binary_bytes(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            text = root / "source.cs"
            binary = root / "package.tgz"
            binary.write_bytes(b"\0\r\n")
            files = [{"path": "source.cs"}, {"path": "package.tgz"}]
            with patch.object(delivery, "ROOT", root):
                text.write_bytes(b"one\r\ntwo\r\n")
                first = delivery.portable_fingerprint(files)
                text.write_bytes(b"one\ntwo\n")
                self.assertEqual(first, delivery.portable_fingerprint(files))
                binary.write_bytes(b"\0\n")
                self.assertNotEqual(first, delivery.portable_fingerprint(files))


class ArtifactValidationTests(unittest.TestCase):
    """Exercise the complete validator with small artifacts, without mocking validate_leg."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.counts = patch.dict(comparison.EXPECTED, {"R4": 1, "R5": 1}, clear=True)
        self.counts.start()
        self.addCleanup(self.counts.stop)

    def write(self, path, value):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")

    def reports(self, directory, assemblies, count=1):
        directory.mkdir(parents=True, exist_ok=True)
        rows, cases = [], []
        for assembly in sorted(assemblies):
            root = ET.Element("TestRun")
            definitions = ET.SubElement(root, "TestDefinitions")
            test = ET.SubElement(definitions, "UnitTest")
            ET.SubElement(test, "TestMethod", codeBase=assembly + ".dll")
            results = ET.SubElement(root, "Results")
            for index in range(count):
                name = assembly + ".Test" + str(index)
                ET.SubElement(results, "UnitTestResult", testName=name, outcome="Passed")
                cases.append({"test": name, "outcome": "Passed"})
            ET.SubElement(ET.SubElement(root, "ResultSummary"), "Counters", total=str(count), passed=str(count), failed="0")
            path = directory / (assembly + ".trx")
            ET.ElementTree(root).write(path, encoding="utf-8")
            rows.append({"assembly": assembly, "sha256": comparison.sha(path)})
        return rows, cases

    def artifact(self, name="artifact", os_name="Windows", passed=()):
        root = self.root / name
        root.mkdir()
        (root / "canonical-tool.nupkg").write_bytes(b"canonical package")
        counts = {"total": 9, "passed": 9, "failed": 0, "skipped": 0}
        summary = {"gate": "G7-platform", "status": "Passed", "os": os_name, "sourceRevision": "current",
            "sourceFingerprint": {"sha256": "raw"}, "portableSourceFingerprint": {"sha256": "portable"}, "testCounts": counts,
            "toolPackageSha256": comparison.sha(root / "canonical-tool.nupkg"), "sdkVersion": "9.0.317", "targetFramework": "net9.0",
            "configuration": "Release", "toolVersion": "1.3.1", "runtimeContract": {"sha256": "reference"}, "policies": {"policy": "locked"},
            "canonicalInstall": {"outsideCheckout": True, "emptyInitialCache": True, "localFeedOnly": True},
            "freshIntegration": {"outsideCheckout": True, "reusedBinObj": False, "reusedCommittedGeneratedSources": False,
                "freshDependencyCache": True, "generatedInputsUnchanged": True}}
        smokes = {}
        for release, version in comparison.FHIR_VERSIONS.items():
            smoke = {"release": release, "expectedFhirVersion": version, "status": "Skipped", "reason": "No endpoint configured"}
            if release in passed:
                smoke = {"release": release, "expectedFhirVersion": version, "status": "Passed", "serverFhirVersion": version,
                    "writesStarted": True, "operations": ["metadata-version", "create", "read", "update", "search", "delete"]}
            smokes[release] = smoke
            self.write(root / "prerequisite" / (release + "-external-smoke.json"), smoke)
        summary["externalServerAcceptance"] = "Passed" if set(passed) == {"R4", "R5"} else "Pending"
        prerequisite = {"status": "Passed", "sourceFingerprint": summary["sourceFingerprint"], "testCounts": counts,
            "externalSmokes": smokes, "externalServerAcceptance": summary["externalServerAcceptance"]}
        self.write(root / "prerequisite/summary.json", prerequisite)
        summary["prerequisiteSha256"] = comparison.sha(root / "prerequisite/summary.json")
        rows, _ = self.reports(root / "prerequisite/sdk/generator/migration/context/test-results", comparison.ASSEMBLIES)
        self.write(root / "prerequisite-reports.json", rows)
        for version, count in ((5, 81), (6, 92)):
            _, cases = self.reports(root / f"fresh-v{version}-results", {f"MyFhirSdk.FhirVersions.V{version}.Tests"}, count)
            self.write(root / f"v{version}-test-cases.json", cases)
            summary[f"freshV{version}Tests"] = count
        summary["generation"] = {}
        for release, version in comparison.FHIR_VERSIONS.items():
            source = root / "generated" / release / "Patient.cs"
            source.parent.mkdir(parents=True)
            source.write_bytes(b"model source")
            path = root / (release + "-generated-hashes.json")
            self.write(path, {"Patient.cs": comparison.sha(source)})
            summary["generation"][release] = {"sourceCount": 1, "fileCount": 1, "deterministic": True,
                "matchesCommittedModels": True, "hashesSha256": comparison.sha(path), "fhirVersion": version, "packageSha256": "input"}
        summary["deployments"] = {}
        negatives = []
        for consumer in ("R4", "R5", "Dual"):
            required = comparison.SHARED | ({"MyFhirSdk.R4.Models.dll", "MyFhirSdk.R5.Models.dll"} if consumer == "Dual"
                else {f"MyFhirSdk.{consumer}.Models.dll"})
            directory = root / "deployments" / consumer
            directory.mkdir(parents=True)
            names = required | {consumer + "Consumer" + suffix for suffix in (".dll", ".deps.json", ".runtimeconfig.json")}
            for filename in names:
                (directory / filename).write_bytes(b"published file")
            path = root / (consumer + "-deployment-hashes.json")
            self.write(path, {p.name: comparison.sha(p) for p in directory.iterdir()})
            summary["deployments"][consumer] = {"status": "Passed", "ownDirectoryOnly": True, "requiredDlls": sorted(required),
                "files": len(names), "hashesSha256": comparison.sha(path)}
            negatives.extend({"consumer": consumer, "missing": dll, "status": "Passed", "exitCode": 1} for dll in sorted(required))
        self.write(root / "missing-dependencies.json", negatives)
        summary["missingDependencyCases"] = len(negatives)
        rows, _ = self.reports(root / "rollback-test-results", comparison.ASSEMBLIES)
        self.write(root / "rollback-regression.json", rows)
        summary["rollback"] = {"status": "Passed", "freshRebuild": True, "currentBranchChanged": False, "mainChanged": False,
            "restoredInputsUnchanged": True, "testCounts": counts, "assemblies": sorted(comparison.ASSEMBLIES),
            "sourceRevision": comparison.ROLLBACK_REVISION, "archiveSha256": "archive", "sourceFiles": 1}
        self.write(root / "rollback-source-hashes.json", {"source.cs": "a" * 64})
        self.write(root / "summary.json", summary)
        return root

    def sync_prerequisite(self, root, prerequisite):
        path = root / "prerequisite/summary.json"
        self.write(path, prerequisite)
        summary = comparison.load(root / "summary.json")
        summary["prerequisiteSha256"] = comparison.sha(path)
        self.write(root / "summary.json", summary)

    def test_complete_artifacts_derive_pending_mixed_and_passed_external_acceptance(self):
        for releases, expected in (((), "Pending"), (("R4",), "Pending"), (("R4", "R5"), "Passed")):
            with self.subTest(releases=releases):
                root = self.artifact(str(len(releases)), passed=releases)
                self.assertEqual(expected, comparison.validate_leg(root)["externalServerAcceptance"])

    def test_platform_summary_cannot_promote_skipped_smokes(self):
        root = self.artifact()
        data = comparison.load(root / "summary.json")
        data["externalServerAcceptance"] = "Passed"
        self.write(root / "summary.json", data)
        with self.assertRaisesRegex(ValueError, "does not match smoke"):
            comparison.validate_leg(root)

    def test_both_summaries_cannot_promote_skipped_smokes_even_with_updated_hash(self):
        root = self.artifact()
        prerequisite = comparison.load(root / "prerequisite/summary.json")
        prerequisite["externalServerAcceptance"] = "Passed"
        self.sync_prerequisite(root, prerequisite)
        data = comparison.load(root / "summary.json")
        data["externalServerAcceptance"] = "Passed"
        self.write(root / "summary.json", data)
        with self.assertRaisesRegex(ValueError, "does not match smoke"):
            comparison.validate_leg(root)

    def test_changed_raw_smoke_must_match_embedded_evidence(self):
        root = self.artifact()
        path = root / "prerequisite/R4-external-smoke.json"
        smoke = comparison.load(path)
        smoke["status"] = "Passed"
        self.write(path, smoke)
        with self.assertRaisesRegex(ValueError, "file/summary mismatch"):
            comparison.validate_leg(root)

    def test_failed_wrong_version_and_incomplete_passed_smokes_are_rejected(self):
        mutations = ({"status": "Failed"}, {"expectedFhirVersion": "5.0.0"}, {"release": "R5"},
            {"status": "Passed"}, {"status": "Passed", "serverFhirVersion": "5.0.0"})
        for index, fields in enumerate(mutations):
            with self.subTest(fields=fields):
                root = self.artifact(str(index))
                prerequisite = comparison.load(root / "prerequisite/summary.json")
                smoke = prerequisite["externalSmokes"]["R4"]
                smoke.update(fields)
                self.write(root / "prerequisite/R4-external-smoke.json", smoke)
                self.sync_prerequisite(root, prerequisite)
                with self.assertRaisesRegex(ValueError, "external smoke|External smoke"):
                    comparison.validate_leg(root)

    def test_missing_raw_smoke_cannot_be_replaced_by_embedded_summary(self):
        root = self.artifact()
        (root / "prerequisite/R4-external-smoke.json").unlink()
        with self.assertRaises(FileNotFoundError):
            comparison.validate_leg(root)

    def test_every_required_deployment_file_is_checked_after_inventory_rehash(self):
        root = self.artifact()
        for consumer in ("R4", "R5", "Dual"):
            directory = root / "deployments" / consumer
            for path in sorted(directory.iterdir()):
                with self.subTest(consumer=consumer, missing=path.name):
                    contents = path.read_bytes()
                    path.unlink()
                    hashes_path = root / (consumer + "-deployment-hashes.json")
                    self.write(hashes_path, {p.name: comparison.sha(p) for p in directory.iterdir()})
                    summary = comparison.load(root / "summary.json")
                    summary["deployments"][consumer].update(files=len(list(directory.iterdir())), hashesSha256=comparison.sha(hashes_path))
                    self.write(root / "summary.json", summary)
                    with self.assertRaisesRegex(ValueError, "Missing required deployment files"):
                        comparison.validate_leg(root)
                    path.write_bytes(contents)
                    self.write(hashes_path, {p.name: comparison.sha(p) for p in directory.iterdir()})
                    summary["deployments"][consumer].update(files=len(list(directory.iterdir())), hashesSha256=comparison.sha(hashes_path))
                    self.write(root / "summary.json", summary)
        self.assertEqual("Passed", comparison.validate_leg(root)["status"])

    def test_comparison_uses_complete_validated_artifacts(self):
        windows = self.artifact("windows")
        linux = self.artifact("linux", "Linux")
        summary = comparison.load(linux / "summary.json")
        summary["rollback"]["archiveSha256"] = "different platform tar metadata"
        self.write(linux / "summary.json", summary)
        result = comparison.compare(windows, linux)
        self.assertEqual("Passed", result["status"])
        self.assertEqual("Pending", result["externalServerAcceptance"])

    def test_changed_rollback_content_is_rejected_even_when_archive_hashes_match(self):
        windows = self.artifact("windows")
        linux = self.artifact("linux", "Linux")
        self.write(linux / "rollback-source-hashes.json", {"source.cs": "b" * 64})
        with self.assertRaisesRegex(ValueError, r"Rollback source files differ: source.cs"):
            comparison.compare(windows, linux)

    def test_missing_or_malformed_rollback_source_inventory_is_rejected(self):
        for index, hashes in enumerate((None, {}, {"source.cs": "invalid"}, {"source.cs": "a" * 64, "extra.cs": "b" * 64})):
            with self.subTest(hashes=hashes):
                root = self.artifact(str(index))
                if hashes is None:
                    (root / "rollback-source-hashes.json").unlink()
                    with self.assertRaises(FileNotFoundError):
                        comparison.validate_leg(root)
                    continue
                self.write(root / "rollback-source-hashes.json", hashes)
                with self.assertRaisesRegex(ValueError, "Rollback source inventory"):
                    comparison.validate_leg(root)

    def test_deployment_file_count_must_match_inventory(self):
        root = self.artifact()
        summary = comparison.load(root / "summary.json")
        summary["deployments"]["R4"]["files"] += 1
        self.write(root / "summary.json", summary)
        with self.assertRaisesRegex(ValueError, "Deployment evidence mismatch"):
            comparison.validate_leg(root)


